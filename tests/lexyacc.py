"""Combined lex/yacc consumer: sanitizer lex, bootstrap V7 yacc, GCC/ASan oracle linked with libln."""
from pathlib import Path
import os
import subprocess
import tempfile
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'tests/lexyacc'
OUT=ROOT/'build/fixtures-lexyacc';OUT.mkdir(parents=True,exist_ok=True)
ENV=dict(os.environ,ASAN_OPTIONS='detect_leaks=0:abort_on_error=1',UBSAN_OPTIONS='halt_on_error=1',
         NX_LEXLIB=str(ROOT/'rootfs/usr/lib/lex'),NX_YACCPAR=str(ROOT/'rootfs/usr/lib/yaccpar'))
CC_HOST=['cc','-std=gnu89','-funsigned-char','-fcommon','-w','-g','-fsanitize=address,undefined','-fno-sanitize-recover=undefined']
def run(cmd,**kw):
    r=subprocess.run(cmd,env=ENV,capture_output=True,timeout=60,**kw)
    assert r.returncode==0 and b'Sanitizer' not in r.stderr and b'runtime error:' not in r.stderr,(cmd,r)
    return r
subprocess.run(['make','build/host-v7-yacc','build/gen-lex/parser.c'],cwd=ROOT,check=True,stdout=subprocess.DEVNULL)
with tempfile.TemporaryDirectory(prefix='nx-lexyacc-') as temp:
    d=Path(temp)
    lex=d/'lex';run([*CC_HOST,'-O1','-I',str(ROOT/'user/lex'),str(ROOT/'build/gen-lex/parser.c'),
        *[str(ROOT/'user/lex'/(n+'.c')) for n in ('lmain','sub1','sub2','header')],'-o',str(lex)])
    for n in ('calc.y','calc.l','calc.in','calc.exp'):(d/n).write_bytes((SRC/n).read_bytes())
    run([str(ROOT/'build/host-v7-yacc'),'-d','calc.y'],cwd=d)
    run([str(lex),'calc.l'],cwd=d)
    # libln is an archive: its main is not linked because the parser defines one.
    lib=d/'libln.a'
    objs=[]
    for n in ('allprint','main','reject','yyless','yywrap'):
        run([*CC_HOST,'-c',str(ROOT/'user/lex/lib'/(n+'.c')),'-o',str(d/(n+'.o'))]);objs.append(n+'.o')
    run(['ar','rcs',str(lib),*objs],cwd=d)
    run([*CC_HOST,'y.tab.c','lex.yy.c','libln.a','-o','calc'],cwd=d)
    r=run([str(d/'calc')],input=(SRC/'calc.in').read_bytes())
    assert r.stdout==(SRC/'calc.exp').read_bytes(),r.stdout
    for n in ('calc.y','calc.l','calc.in','calc.exp','y.tab.c','y.tab.h','lex.yy.c'):(OUT/n).write_bytes((d/n).read_bytes())
print('PASS: combined lex/yacc calculator generated by the retained generators, run under ASan/UBSan, linked with libln and checked against the expected output')
