"""Sanitize the native V7 make engine/parser/archive adapters."""
import os
from pathlib import Path
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[1]
SOURCES=['main','doname','misc','files','dosys','ident','parser','archive']


def build(binary):
    subprocess.run(['cc','-Dunix','-DNX_MAKE_HOST','-std=gnu89','-funsigned-char','-fno-builtin','-fno-pie','-no-pie','-w','-fsanitize=address,undefined','-g',*[str(ROOT/'user/v7/cmd/make'/f'{s}.c') for s in SOURCES],'-o',str(binary)],check=True)


def main():
    with tempfile.TemporaryDirectory() as directory:
        root=Path(directory);binary=root/'make';build(binary)
        env=dict(os.environ,ASAN_OPTIONS='detect_leaks=0',UBSAN_OPTIONS='halt_on_error=1')
        def run(*args,status=0,contains=None,data=None):
            result=subprocess.run([str(binary),*args],cwd=root,input=data,text=True,capture_output=True,env=env,timeout=5)
            assert result.returncode==status,(args,result)
            assert 'Sanitizer' not in result.stderr and 'runtime error' not in result.stderr,result
            if contains is not None:assert contains in result.stdout,(args,result,contains)
            return result
        def write(name,text,stamp=100):
            p=root/name;p.write_text(text);os.utime(p,(stamp,stamp));return p
        write('Makefile','MSG=file\nall: output\n\t@echo $(MSG):$@:$?\noutput: input\n\t@cat input > $@\n')
        write('input','alpha\n',0)
        run('-q',status=255);run(contains='file:all:output');assert (root/'output').read_text()=='alpha\n'
        run('output',contains='up to date');run('-q','output')
        run('-q','output','all',status=255)
        write('input','beta\n',2000000000)
        run('-n','output',contains='cat input > output');assert (root/'output').read_text()=='alpha\n'
        run('output');assert (root/'output').read_text()=='beta\n'
        run('MSG=argument',contains='argument:all:output')
        run('-p','output',contains='Macros:')
        run('-t','output',contains='touch(output)')
        write('failure','bad:\n\tfalse\nnext:\n\t@echo continued\n')
        run('-f','failure','bad',status=1,contains='Error code 1')
        run('-k','-f','failure','bad','next',status=1,contains='continued')
        run('-i','-f','failure','bad',contains='ignored')
        write('ignored','bad:\n\t-false\n\t@echo survived\n')
        run('-f','ignored','bad',contains='survived')
        write('double','all::\n\t@echo first\nall::\n\t@echo second\n')
        run('-f','double',contains='first\nsecond');run('-q','-f','double',status=255)
        write('suffix','.SUFFIXES:\n.SUFFIXES: .src .dst\n.src.dst:\n\t@cp $< $@; echo stem:$*\nresult.dst:\n')
        write('result.src','inferred\n');run('-f','suffix','result.dst',contains='stem:result');assert (root/'result.dst').read_text()=='inferred\n'
        write('wildcard','all: *.src\n\t@echo $?\n');run('-f','wildcard',contains='result.src')
        write('special','.IGNORE:\n.SILENT:\nall:\n\tfalse\n\techo special\n')
        result=run('-f','special',contains='special');assert 'echo special' not in result.stdout
        write('fallback','.DEFAULT:\n\t@echo fallback:$<\n')
        run('-f','fallback','missing',contains='fallback:missing')
        write('several','first second:\n\t@echo built:$@\n')
        run('-r','-f','several','first','second',contains='built:first\nbuilt:second')

        write('inline','VAR = hel\\\n lo\nall: ; @echo $(VAR) # literal\n');run('-f','inline',contains='hel lo')
        run('-f','-',contains='stdin',data='all:\n\t@echo stdin\n')
        write('one','NAME=multi\n');write('two','all:\n\t@echo $(NAME)\n');run('-f','one','-f','two',contains='multi')
        # Portable archive names and native ELF symbols, independently generated by host tools.
        write('member.c','int exported(void) { return 1; }\n')
        subprocess.run(['cc','-c',str(root/'member.c'),'-o',str(root/'long_member_name.o')],check=True)
        subprocess.run(['ar','rcU',str(root/'lib.a'),str(root/'long_member_name.o')],check=True)
        write('archives','member: lib.a(long_member_name.o)\n\t@echo member-ok\nsymbol: lib.a((exported))\n\t@echo symbol-ok\n')
        run('-f','archives','member',contains='member-ok');run('-f','archives','symbol',contains='symbol-ok')
        subprocess.run(['ar','sD',str(root/'lib.a')],check=True)
        run('-f','archives','symbol',contains='symbol-ok')
        write('archivebad','all: broken.a(member)\n');write('broken.a','!<arch>\nBAD')
        run('-f','archivebad',status=1)
        import struct
        original=(root/'long_member_name.o').read_bytes()
        for payload in [b'\x7fELF',original[:40]+struct.pack('<Q',2**63)+original[48:]]:
            header=b'bad.o/          '+b'1           '+b'0     '+b'0     '+b'100644  '+str(len(payload)).encode().ljust(10)+b'`\n'
            assert len(header)==60
            (root/'broken.a').write_bytes(b'!<arch>\n'+header+payload+(b'\n' if len(payload)%2 else b''))
            write('archivebad','all: broken.a((exported))\n')
            run('-f','archivebad',status=1)

        for text in ['target without colon\n','\torphan\n','A=$(A)\nall:\n\techo $(A)\n','all: all\n', 'x'*1600+'\n','all:\n\techo '+('x '*210)+'\n','A='+('x'*1200)+'\nall:\n\techo $(A)$(A)$(A)\n']:
            write('invalid',text);run('-f','invalid',status=1)
        write('invalid',''.join(f'n{i}: n{i+1}\n' for i in range(34))+'n34:\n');run('-f','invalid',status=1)
        write('invalid','all:\n\techo $('+'x'*101+')\n');run('-f','invalid',status=1)
        write('invalid',' '.join('t'+str(i) for i in range(41))+':\n');run('-f','invalid',status=1)
    print('PASS: make ASan/UBSan graph/timestamps, macros, suffix/wildcard rules, recipes, flags, archives/ELF and malformed input')

if __name__=='__main__':main()
