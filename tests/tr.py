"""tr: ranges, octal escapes, -c/-d/-s, NUL deletion, all bytes and literal argument safety."""
from v7_command import Command
c=Command('tr')
c.check(['a-z','A-Z'],'HELLO, WORLD\n',data='hello, world\n')
c.check(['-d','l'],'heo\n',data='hello\n')
c.check(['-cs','a-z','\\012'],'hello\nworld\n',data='hello, world\n')
c.check(['-s','a-z','a-z'],'abc d\n',data='aabbcc dddd\n')
c.check(['-s','x','y'],'ay b\n',data='axxx b\n')
c.check(['abc','x'],'xxxd\n',data='abcd\n')
c.check(['\\170','Y'],'aYb\n',data='axb\n')
c.check(['a-','xy'],'xbcy\n',data='abc-\n')
c.check(['-d'],'ab\n',data='a\0b\n')
c.check([],'same\n',data='same\n')
every=bytes(range(1,256))
c.check(['\\001-\\377','\\001-\\377'],every,data=every)
c.check(['-d','\\001-\\377'],'',data=every)
c.check(['-cd','a'],'aa',data=every+b'a')
c.check(['\\200-\\377','x'],b'x'*128,data=bytes(range(128,256)))
print('PASS: tr ASan/UBSan ranges, octal, complement/delete/squeeze, NUL and all 255 byte values')
