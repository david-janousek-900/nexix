#ifndef NEXIX_ABI_PHYS_H
#define NEXIX_ABI_PHYS_H
#include <stdint.h>
#define NX_PHYS_WINDOWS 8U
#define NX_PHYS_PAGES 2U
#define NX_PHYS_PAGE_SIZE 4096UL
#define NX_PHYS_BASE UINT64_C(0x600000000000)
#define NX_PHYS_STRIDE (NX_PHYS_PAGES * NX_PHYS_PAGE_SIZE)
#define NX_PHYS_ADDRESS(slot) (NX_PHYS_BASE + (uint64_t)(slot) * NX_PHYS_STRIDE)
#define NX_PHYS_VGA_BASE UINT64_C(0xb8000)
#define NX_PHYS_VGA_END UINT64_C(0xc0000)
#define NX_PHYS_FRAMES 128U
#endif
