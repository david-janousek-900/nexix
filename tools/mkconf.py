"""Generate the native kernel driver link configuration; never execute V7 mkconf."""
import argparse
import json
from pathlib import Path

DRIVERS = {
    'console': ('build/serial.o', 'kernel/serial.c'),
    'terminal2': ('build/serial_secondary.o', 'kernel/serial_secondary.c'),
    'vga': ('build/vga.o', 'kernel/vga.c'),
    'keyboard': ('build/keyboard.o', 'kernel/keyboard.c'),
    'local-console': ('build/local_console.o', 'kernel/local_console.c'),
    'ide': ('build/ide.o', 'kernel/ide.c'),
    'rtc': ('build/rtc.o', 'kernel/arch/x86_64/rtc.c'),
    'fpu': ('build/fpu.o', 'kernel/arch/x86_64/fpu.c'),
}


def configure(config):
    if not isinstance(config, dict) or set(config) != {'schema_version', 'architecture', 'root', 'memory', 'drivers'}:
        raise ValueError('unknown or missing kernel configuration key')
    if config['schema_version'] != 1 or config['architecture'] != 'x86_64':
        raise ValueError('unsupported schema or architecture')
    if config['root'] != 'ide-with-bootstrap-fallback' or config['memory'] != 'resident':
        raise ValueError('unsupported root or memory model')
    drivers = config['drivers']
    if not isinstance(drivers, list) or any(not isinstance(d, str) for d in drivers):
        raise ValueError('drivers must be names')
    if len(drivers) != len(set(drivers)) or set(drivers) != set(DRIVERS):
        raise ValueError('native boot profile requires exactly console, terminal2, vga, keyboard, local-console, ide, rtc, fpu')
    # Fixed canonical order makes semantically identical configurations reproducible.
    return '# Generated by tools/mkconf.py; do not edit.\nNATIVE_CONFIG_OBJECTS := ' + ' '.join(DRIVERS[d][0] for d in DRIVERS) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    try:
        text = configure(json.loads(args.input.read_text()))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary = args.output.with_suffix('.tmp')
        temporary.write_text(text)
        temporary.replace(args.output)
    except (OSError, ValueError) as error:
        parser.exit(1, f'mkconf: {error}\n')


if __name__ == '__main__':
    main()
